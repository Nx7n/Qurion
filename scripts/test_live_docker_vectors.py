#!/usr/bin/env python3
"""test_live_docker_vectors.py — Test Qurion with REAL Open5GS Docker AVPs.

Extracts the real, authentic Milenage authentication vectors generated by
the live Open5GS HSS container during srsUE attach and feeds them into
the Qurion PQC protection pipeline (HSSAgent -> DiameterRelay -> MMEAgent).
"""

import os
import sys
import time

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from src.crypto.kem import generate_keypair as kem_keygen
from src.crypto.signatures import generate_signing_keypair as sig_keygen
from src.gateway.hss_agent import HSSAgent
from src.gateway.mme_agent import MMEAgent
from src.gateway.relay import DiameterRelay
from src.diameter.avp_codec import (
    DiameterMessage, DiameterAVP, AVPBuilder,
    AVP_AUTH_INFO, AVP_E_UTRAN_VECTOR,
    AVP_RAND, AVP_XRES, AVP_AUTN, AVP_KASME,
    AVP_QURION_PROTECTED_AV, QURION_VENDOR_ID,
    S6A_APPLICATION_ID, AIA_COMMAND_CODE
)

GREEN = '\033[0;32m'
BLUE = '\033[0;34m'
YELLOW = '\033[1;33m'
NC = '\033[0m'

def log_step(msg):
    print(f"\n{BLUE}=== {msg} ==={NC}")

def pass_step(msg):
    print(f"{GREEN}[✓]{NC} {msg}")

def main():
    print(f"{BLUE}================================================================={NC}")
    print(f"{BLUE} PQC Protection Verification with REAL Docker Open5GS Vectors{NC}")
    print(f"{BLUE}================================================================={NC}")

    # REAL Milenage vectors emitted by HSS container during srsUE attach:
    real_rand = bytes.fromhex("A2 84 57 5A 44 9B A2 71 43 DD 9E B9 FA AA E7 EB")
    real_xres = bytes.fromhex("27 9E 78 59 20 22 A1 6F")
    real_autn = bytes.fromhex("B9 03 97 13 DF C3 80 00 1F 09 CC DF 9A EB AC 88")
    real_kasme = bytes.fromhex("99 A1 E1 13 F0 89 CC 8A 19 16 C5 A0 BA F3 44 83 59 CD B7 4A 08 D7 ED 3E EE B7 79 64 4F A7 83 25")

    log_step("1. Real Open5GS Docker Milenage Vectors")
    print(f"  RAND  (16B): {real_rand.hex()}")
    print(f"  XRES  (8B):  {real_xres.hex()}")
    print(f"  AUTN  (16B): {real_autn.hex()}")
    print(f"  KASME (32B): {real_kasme.hex()}")
    pass_step("Sourced directly from live Open5GS HSS container log execution.")

    # 2. Key Generation
    log_step("2. Initializing NIST PQC Keys (ML-KEM-768 & ML-DSA-65)")
    hss_kem_pub, hss_kem_priv = kem_keygen()
    hss_sign_pub, hss_sign_priv = sig_keygen()
    mme_kem_pub, mme_kem_priv = kem_keygen()
    mme_sign_pub, mme_sign_priv = sig_keygen()
    pass_step("Generated fresh post-quantum keypairs for HSS and MME.")

    # 3. Agents
    log_step("3. Initializing Gateway Agents and Diameter Relay")
    hss_agent = HSSAgent("hss.localdomain", "localdomain", hss_sign_priv, hss_sign_pub, hss_kem_priv, hss_kem_pub, None, None, None)
    mme_agent = MMEAgent("mme.localdomain", "localdomain", mme_sign_priv, mme_sign_pub, mme_kem_priv, mme_kem_pub, None, None, None)
    relay = DiameterRelay()
    pass_step("Agents initialized.")

    # 4. Construct S6a AIA matching Open5GS 3GPP Grouped AVP format
    log_step("4. Constructing 3GPP Grouped Authentication-Info AVP")
    eutran_vector_avps = [
        DiameterAVP(code=AVP_RAND, flags=0xC0, vendor_id=10415, data=real_rand),
        DiameterAVP(code=AVP_XRES, flags=0xC0, vendor_id=10415, data=real_xres),
        DiameterAVP(code=AVP_AUTN, flags=0xC0, vendor_id=10415, data=real_autn),
        DiameterAVP(code=AVP_KASME, flags=0xC0, vendor_id=10415, data=real_kasme),
    ]
    eutran_vector_body = b"".join(a.encode() for a in eutran_vector_avps)
    eutran_vector = DiameterAVP(code=AVP_E_UTRAN_VECTOR, flags=0xC0, vendor_id=10415, data=eutran_vector_body)
    
    auth_info = DiameterAVP(code=AVP_AUTH_INFO, flags=0xC0, vendor_id=10415, data=eutran_vector.encode())

    unprotected_msg = DiameterMessage(
        command_code=AIA_COMMAND_CODE, application_id=S6A_APPLICATION_ID,
        is_request=False, is_proxiable=True, avps=[auth_info]
    )
    raw_unprotected = unprotected_msg.encode()
    pass_step(f"Open5GS format AIA built ({len(raw_unprotected)} bytes wire length).")

    # 5. Protect
    log_step("5. HSS Interception: Encapsulation & AES-256-GCM AEAD Encryption")
    t0 = time.perf_counter_ns()
    protected_msg = hss_agent.process_outgoing_aia(unprotected_msg, mme_kem_pub)
    protect_time_ns = time.perf_counter_ns() - t0
    raw_protected = protected_msg.encode()
    
    assert protected_msg.find_avp(AVP_QURION_PROTECTED_AV, QURION_VENDOR_ID) is not None, "Protected AVP missing"
    assert protected_msg.find_avp(AVP_AUTH_INFO) is None, "Plaintext Auth-Info remained exposed!"
    pass_step(f"Grouped Authentication-Info encrypted into Qurion envelope in {protect_time_ns/1000:.1f} µs.")
    pass_step(f"Protected wire length: {len(raw_protected)} bytes (+{len(raw_protected) - len(raw_unprotected)} bytes overhead).")

    # 6. Relay
    log_step("6. Diameter Proxy / Relay Forwarding")
    relayed_msg = relay.forward(protected_msg, "HSS->MME")
    assert relay.has_protected_avp(relayed_msg), "Relay did not retain protected payload"
    pass_step("Relay forwarded message without decryption.")

    # 7. MME Decapsulate
    log_step("7. MME Interception: ML-KEM Decapsulation & Payload Decryption")
    t1 = time.perf_counter_ns()
    decrypted_msg = mme_agent.process_incoming_aia(relayed_msg)
    decrypt_time_ns = time.perf_counter_ns() - t1
    pass_step(f"MME restored original message in {decrypt_time_ns/1000:.1f} µs.")

    # 8. Unpack and verify
    log_step("8. Validating Decrypted Material Against Docker Ground Truth")
    restored_auth_info = decrypted_msg.find_avp(AVP_AUTH_INFO)
    assert restored_auth_info is not None, "Restored Authentication-Info missing"
    
    # Unpack grouped AVPs
    inner_avps = DiameterAVP.decode_all(restored_auth_info.data)
    inner_vector = inner_avps[0]
    vector_avps = DiameterAVP.decode_all(inner_vector.data)
    
    vector_dict = {a.code: a.data for a in vector_avps}
    assert vector_dict[AVP_RAND] == real_rand, "RAND mismatch"
    assert vector_dict[AVP_XRES] == real_xres, "XRES mismatch"
    assert vector_dict[AVP_AUTN] == real_autn, "AUTN mismatch"
    assert vector_dict[AVP_KASME] == real_kasme, "KASME mismatch"
    
    pass_step("RAND matches real Docker HSS value!")
    pass_step("XRES matches real Docker HSS value!")
    pass_step("AUTN matches real Docker HSS value!")
    pass_step("KASME matches real Docker HSS value!")
    pass_step(f"Roundtrip PQC processing overhead: {(protect_time_ns + decrypt_time_ns)/1000:.1f} µs.")

    print(f"\n{GREEN}================================================================={NC}")
    print(f"{GREEN} 100% SUCCESS: REAL DOCKER OPEN5GS VECTORS SAFELY PROTECTED{NC}")
    print(f"{GREEN}================================================================={NC}\n")

if __name__ == "__main__":
    main()
